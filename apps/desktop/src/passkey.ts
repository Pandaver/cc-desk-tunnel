import {
  browserSupportsWebAuthn,
  startAuthentication,
  startRegistration,
  WebAuthnAbortService,
} from '@simplewebauthn/browser';
import type {
  PublicKeyCredentialCreationOptionsJSON,
  PublicKeyCredentialRequestOptionsJSON,
} from '@simplewebauthn/browser';
import { webLoginStateSchema } from '@cc-desk-tunnel/protocol';
import type { WebProof } from '@cc-desk-tunnel/protocol';
import { z } from 'zod';
import { browserRequest } from './browser-api.ts';

export const supportsPasskeys = () => window.isSecureContext && browserSupportsWebAuthn();
export const cancelPasskey = () => WebAuthnAbortService.cancelCeremony();
export function passkeyError(error: unknown) {
  if (error instanceof Error && ['NotAllowedError', 'AbortError'].includes(error.name))
    return '验证已取消或超时，请重试。';
  if (error instanceof Error && error.name === 'InvalidStateError')
    return '此认证器已保存通行密钥，请选择其他认证器。';
  if (error instanceof Error && ['ConstraintError', 'NotSupportedError'].includes(error.name))
    return '此认证器不支持所需的设备验证，请尝试其他设备或密码管理器。';
  if (error instanceof Error && error.name === 'SecurityError')
    return '请确认当前域名和 HTTPS 证书有效，再重新验证。';
  return error instanceof Error ? error.message : '通行密钥验证失败，请重试。';
}

// These envelopes are generated by the same service. The WebAuthn library validates and converts
// the public-key options, while the server verifies the signed response and its one-time challenge.
const authenticationOptions = z.object({
  challengeId: z.uuid(),
  options: z.custom<PublicKeyCredentialRequestOptionsJSON>(
    (value) => !!value && typeof value === 'object' && 'challenge' in value,
  ),
});
const registrationOptions = z.object({
  challengeId: z.uuid(),
  options: z.custom<PublicKeyCredentialCreationOptionsJSON>(
    (value) => !!value && typeof value === 'object' && 'challenge' in value,
  ),
  name: z.string(),
});
async function authenticate(kind: 'login' | 'proof', signal?: AbortSignal) {
  if (!supportsPasskeys()) throw new Error('请使用支持通行密钥的浏览器和可信 HTTPS 地址。');
  const result = authenticationOptions.parse(
    await browserRequest(`passkey/${kind}/options`, {}, signal),
  );
  signal?.throwIfAborted();
  const response = await startAuthentication({ optionsJSON: result.options });
  signal?.throwIfAborted();
  return browserRequest(
    `passkey/${kind}/verify`,
    { challengeId: result.challengeId, response },
    signal,
  );
}
export async function loginWithPasskey(signal?: AbortSignal) {
  return webLoginStateSchema.parse(await authenticate('login', signal));
}
export async function resolveWebProof(proof: WebProof, signal?: AbortSignal): Promise<WebProof> {
  if (!('passkey' in proof)) return proof;
  const result = z.object({ proof: z.string().min(1) }).parse(await authenticate('proof', signal));
  return { passkey: result.proof };
}
export async function registerPasskey(grant: string, signal?: AbortSignal) {
  if (!supportsPasskeys()) throw new Error('请使用支持通行密钥的浏览器和可信 HTTPS 地址。');
  const result = registrationOptions.parse(
    await browserRequest('passkey/register/options', { grant }, signal),
  );
  signal?.throwIfAborted();
  const response = await startRegistration({ optionsJSON: result.options });
  signal?.throwIfAborted();
  return z
    .object({ registered: z.literal(true), id: z.uuid() })
    .parse(
      await browserRequest(
        'passkey/register/verify',
        { challengeId: result.challengeId, response },
        signal,
      ),
    );
}
export type PasskeyLink = { token: string };
export async function describePasskeyLink(link: PasskeyLink, signal: AbortSignal) {
  return z
    .object({ name: z.string(), expiresAt: z.iso.datetime() })
    .parse(await browserRequest('passkey/register/options', { grant: link.token }, signal));
}
// Keep short-lived authorizations out of subsequent links, history and referrers. No ceremony starts
// here: the destination still asks the user to confirm the purpose and server on the page.
export function readPasskeyLink(): PasskeyLink | null {
  const fragment = new URLSearchParams(location.hash.slice(1));
  const token = fragment.get('passkey-register');
  if (token) {
    history.replaceState(history.state, '', `${location.pathname}${location.search}`);
    return { token };
  }
  return null;
}
